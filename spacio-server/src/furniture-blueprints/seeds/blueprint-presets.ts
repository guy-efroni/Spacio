import {
  IFurnitureBlueprint,
  IFurniturePart,
  IVector3D,
  TMaterialFinish,
  TPartShape,
} from '../interfaces/furniture-blueprint.interface';

function slot(label: string, color: string, finish: TMaterialFinish) {
  const pbr: Record<TMaterialFinish, { roughness: number; metalness: number }> =
    {
      matte: { roughness: 0.9, metalness: 0 },
      satin: { roughness: 0.45, metalness: 0.05 },
      gloss: { roughness: 0.15, metalness: 0.05 },
      metallic: { roughness: 0.25, metalness: 0.85 },
    };
  return {
    label,
    color,
    finish,
    roughness: pbr[finish].roughness,
    metalness: pbr[finish].metalness,
  };
}

function part(
  id: string,
  name: string,
  shape: TPartShape,
  width: number,
  height: number,
  depth: number,
  x: number,
  y: number,
  z: number,
  materialSlot: string,
): IFurniturePart {
  const position: IVector3D = { x, y, z };
  return {
    id,
    name,
    shape,
    dimensions: { width, height, depth },
    position,
    rotation: { x: 0, y: 0, z: 0 },
    materialSlot,
  };
}

function legs(
  prefix: string,
  count: number,
  width: number,
  height: number,
  depth: number,
  xs: number[],
  zs: number[],
): IFurniturePart[] {
  const result: IFurniturePart[] = [];
  for (let index = 0; index < count; index += 1) {
    result.push(
      part(
        `${prefix}-leg-${index + 1}`,
        `Leg ${index + 1}`,
        'box',
        width,
        height,
        depth,
        xs[index],
        height / 2,
        zs[index],
        'legs',
      ),
    );
  }
  return result;
}

